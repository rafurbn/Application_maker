import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicDir = path.join(root, 'public');
const outDir = path.join(publicDir, 'icons');
mkdirSync(outDir, { recursive: true });

const appIcon = readFileSync(path.join(publicDir, 'icon.svg'));
const maskableIcon = readFileSync(path.join(publicDir, 'icon-maskable.svg'));

/** @type {{ file: string, size: number, source: Buffer }[]} */
const targets = [
  { file: 'icon-192.png', size: 192, source: appIcon },
  { file: 'icon-512.png', size: 512, source: appIcon },
  { file: 'icon-maskable-192.png', size: 192, source: maskableIcon },
  { file: 'icon-maskable-512.png', size: 512, source: maskableIcon },
  { file: 'apple-touch-icon.png', size: 180, source: maskableIcon },
  { file: 'favicon-48.png', size: 48, source: appIcon },
  { file: 'favicon-32.png', size: 32, source: appIcon },
];

for (const target of targets) {
  await sharp(target.source, { density: 300 })
    .resize(target.size, target.size, { fit: 'contain', background: { alpha: 0, r: 0, g: 0, b: 0 } })
    .png()
    .toFile(path.join(outDir, target.file));
  console.log(`created public/icons/${target.file} (${target.size}x${target.size})`);
}

// The SVG sources are kept for browsers that render them crisply at any size.
writeFileSync(path.join(outDir, 'README.txt'), 'Generated by `npm run icons`. Do not edit by hand.\n');
console.log('done');
